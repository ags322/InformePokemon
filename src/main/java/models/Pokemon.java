package models;

public class Pokemon {

    private int id;
    private String nombre;
    private String tipo;
    private int nivel;
    private int ps;

    public Pokemon() {
    }

    public int getId() {
        return id;
    }

    public String getNombre() {
        return nombre;
    }

    public String getTipo() {
        return tipo;
    }

    public int getNivel() {
        return nivel;
    }

    public int getPs() {
        return ps;
    }

}
